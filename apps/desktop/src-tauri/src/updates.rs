use crate::{trusted, Broker};
use serde_json::{json, Value};
use tauri::{Manager, State, WebviewWindow};
use tauri_plugin_updater::UpdaterExt;

static INSTALLING: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

#[tauri::command]
pub async fn desktop_update(
    window: WebviewWindow,
    broker: State<'_, Broker>,
    channel: String,
    confirm_version: Option<String>,
) -> Result<Value, String> {
    trusted(&window)?;
    let _installation = if confirm_version.is_some() {
        Some(
            INSTALLING
                .try_lock()
                .map_err(|_| "A desktop update is already in progress")?,
        )
    } else {
        None
    };
    let endpoint = match channel.as_str() {
        "stable" => option_env!("ASSENTOR_STABLE_UPDATE_URL"),
        "beta" => option_env!("ASSENTOR_BETA_UPDATE_URL"),
        _ => return Err(String::from("Unknown Assentor update channel")),
    };
    let Some((key, endpoint)) = option_env!("ASSENTOR_UPDATER_PUBLIC_KEY").zip(endpoint) else {
        return Ok(json!({"enabled": false}));
    };
    if key.is_empty() || !endpoint.starts_with("https://") {
        return Err(String::from("Invalid desktop updater configuration"));
    }
    let updater = window
        .app_handle()
        .updater_builder()
        .pubkey(key)
        .endpoints(vec![endpoint
            .parse()
            .map_err(|_| "Invalid desktop update URL")?])
        .map_err(|_| "Invalid desktop update channel")?
        .build()
        .map_err(|_| "Could not initialize the desktop updater")?;
    let update = updater
        .check()
        .await
        .map_err(|_| "Could not check the desktop update channel")?;
    if let Some(announced) = update {
        let update = updater
            .restore_update(announced.raw_json)
            .map_err(|_| "Could not verify the desktop update metadata")?
            .ok_or("The desktop update is no longer applicable")?;
        let version = update.version.clone();
        if let Some(expected) = confirm_version {
            if expected != version {
                return Err(String::from("The available version changed; check again"));
            }
            let bytes = update
                .download(|_, _| {}, || {})
                .await
                .map_err(|_| "Could not download or verify the signed update")?;
            broker.shutdown().await;
            if update.install(bytes).is_err() {
                broker.reopen_after_failed_update().await;
                return Err(String::from("Could not install the verified update"));
            }
            #[cfg(not(windows))]
            {
                use std::sync::atomic::{AtomicU8, Ordering};
                window
                    .app_handle()
                    .state::<AtomicU8>()
                    .store(crate::DESKTOP_EXIT_READY, Ordering::Release);
                window.app_handle().restart();
            }
        }
        Ok(json!({"enabled": true, "version": version}))
    } else {
        Ok(json!({"enabled": true}))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{env, fs, path::PathBuf};

    #[test]
    #[ignore = "requires a temporary Tauri signing fixture generated by CI"]
    fn verifies_a_version_bound_update_and_rejects_tampering() {
        let dir =
            PathBuf::from(env::var_os("ASSENTOR_SIGNING_FIXTURE_DIR").expect("fixture directory"));
        let key = fs::read_to_string(dir.join("mock.key.pub")).unwrap();
        let signature = fs::read_to_string(dir.join("artifact.bin.sig")).unwrap();
        let bytes = fs::read(dir.join("artifact.bin")).unwrap();
        let mut context = tauri::test::mock_context(tauri::test::noop_assets());
        context
            .config_mut()
            .plugins
            .0
            .insert("updater".into(), json!({"pubkey": key.trim()}));
        let app = tauri::test::mock_builder()
            .plugin(tauri_plugin_updater::Builder::new().build())
            .build(context)
            .unwrap();
        let updater = app
            .updater_builder()
            .pubkey(key.trim())
            .endpoints(vec!["https://example.invalid/manifest.json"
                .parse()
                .unwrap()])
            .unwrap()
            .build()
            .unwrap();
        let restore = |version: &str| {
            updater
                .restore_update(json!({
                    "version": version,
                    "url": "https://example.invalid/artifact.bin",
                    "signature": signature.trim(),
                }))
                .unwrap()
                .unwrap()
        };
        let valid = restore("99.0.0");
        assert!(valid.verify(&bytes).is_ok());
        let mut tampered = bytes.clone();
        tampered.push(1);
        assert!(valid.verify(&tampered).is_err());
        assert!(restore("99.0.1").verify(&bytes).is_err());
    }
}
